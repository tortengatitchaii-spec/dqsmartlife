export function calculateDqScore(answers: Record<string, number>): {
  overallScore: number;
  skillScores: Record<SkillId, number>;
  levelName: string;
  levelTier: 'excellent' | 'good' | 'developing' | 'need_learning';
  topSkills: SkillId[];
  growthSkills: SkillId[];
} {
  const skillTotals: Record<SkillId, { total: number; count: number }> = {
    identity: { total: 0, count: 0 },
    screen_time: { total: 0, count: 0 },
    cyberbullying: { total: 0, count: 0 },
    cybersecurity: { total: 0, count: 0 },
    privacy: { total: 0, count: 0 },
    critical_thinking: { total: 0, count: 0 },
    footprints: { total: 0, count: 0 },
    empathy: { total: 0, count: 0 }
  };

  DQ_ASSESSMENT_QUESTIONS.forEach((q) => {
    const score = answers[q.id] ?? 0;
    skillTotals[q.skillId].total += score;
    skillTotals[q.skillId].count += 1;
  });

  const skillScores = {} as Record<SkillId, number>;
  let totalSum = 0;
  let countSum = 0;

  (Object.keys(skillTotals) as SkillId[]).forEach((skillId) => {
    const avg = skillTotals[skillId].count > 0 
      ? Math.round(skillTotals[skillId].total / skillTotals[skillId].count) 
      : 0;
    skillScores[skillId] = avg;
    totalSum += skillTotals[skillId].total;
    countSum += skillTotals[skillId].count;
  });

  const overallScore = countSum > 0 ? Math.round(totalSum / countSum) : 0;

  let levelName = 'ควรเรียนรู้เพิ่มเติม';
  let levelTier: 'excellent' | 'good' | 'developing' | 'need_learning' = 'need_learning';

  if (overallScore >= 80) {
    levelName = 'DQ ดีเยี่ยม (Exceptional)';
    levelTier = 'excellent';
  } else if (overallScore >= 60) {
    levelName = 'DQ ดี (Proficient)';
    levelTier = 'good';
  } else if (overallScore >= 40) {
    levelName = 'ควรพัฒนา (Developing)';
    levelTier = 'developing';
  } else {
    levelName = 'ควรเรียนรู้เพิ่มเติม (Needs Learning)';
    levelTier = 'need_learning';
  }

  // Sort skills
  const sortedSkills = (Object.keys(skillScores) as SkillId[]).sort(
    (a, b) => skillScores[b] - skillScores[a]
  );

  const topSkills = sortedSkills.slice(0, 2);
  const growthSkills = sortedSkills.slice(-2).reverse();

  return {
    overallScore,
    skillScores,
    levelName,
    levelTier,
    topSkills,
    growthSkills
  };
}
