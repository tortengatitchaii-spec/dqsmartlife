export function getLocalDqResponse(prompt: string): string {
  const p = prompt.toLowerCase();
  
  if (p.includes('8 ทักษะ') || p.includes('มีอะไรบ้าง') || p.includes('กรอบแนวคิด') || p.includes('ทักษะ')) {
    return `ความฉลาดทางดิจิทัล (Digital Intelligence: DQ) ตามกรอบของ สสวท. (เขียนโดย ฉัตรพงศ์ ชูแสงนิล) ประกอบด้วย 8 ทักษะสำคัญดังนี้ครับ:

1. **Digital Citizen Identity (เอกลักษณ์พลเมืองดิจิทัล)**: การสร้างและบริหารอัตลักษณ์บนโลกออนไลน์และชีวิตจริงอย่างเหมาะสม รับผิดชอบ ไม่ละเมิดกฎหมายและจริยธรรม
2. **Screen Time Management (การบริหารจัดการเวลาบนโลกดิจิทัล)**: การจัดสรรเวลาหน้าจอกับชีวิตจริง ป้องกันอาการเสพติดและปัญหาสุขภาพ
3. **Cyberbullying Management (การจัดการการกลั่นแกล้งบนไซเบอร์)**: การรับมือ ป้องกัน และไม่ร่วมมือกับการกลั่นแกล้งบนโลกออนไลน์
4. **Cybersecurity Management (การจัดการความปลอดภัยบนโลกไซเบอร์)**: การปกป้องรหัสผ่าน บัญชี ข้อมูล และอุปกรณ์จากมัลแวร์และแฮกเกอร์
5. **Privacy Management (การจัดการความเป็นส่วนตัว)**: การปกป้องข้อมูลส่วนบุคคล (PDPA) และเคารพสิทธิความเป็นส่วนตัวของผู้อื่น
6. **Critical Thinking (การคิดอย่างมีวิจารณญาณ)**: การแยกแยะข้อเท็จจริง ตรวจสอบข่าวปลอม (Fake News) และตั้งคำถามกับข้อมูลก่อนเชื่อหรือแชร์
7. **Digital Footprints (ร่องรอยทางดิจิทัล)**: การตระหนักว่าทุกโพสต์ คอมเมนต์ หรือการค้นหาจะทิ้งประวัติที่อาจส่งผลต่อการเรียนและหน้าที่การงานในอนาคต
8. **Digital Empathy (ความเห็นอกเห็นใจบนโลกดิจิทัล)**: ความเข้าใจอารมณ์ความรู้สึกผู้อื่นบนโลกไซเบอร์ มีมิตรไมตรี คิดก่อนพิมพ์ และเคารพความเห็นต่าง`;
  }

  if (p.includes('fake news') || p.includes('ข่าวปลอม') || p.includes('ข่าวลวง') || p.includes('วิจารณญาณ') || p.includes('deepfake')) {
    return `💡 **การรับมือกับข่าวปลอม (Fake News) & Deepfake ด้วยทักษะ Critical Thinking**:

1. **ตรวจสอบแหล่งที่มา (Source Verification)**: เว็บไซต์ที่เผยแพร่มีความน่าเชื่อถือหรือไม่ มี URL แปลกๆ หรือสะกดเลียนแบบสำนักข่าวดังหรือไม่
2. **สังเกตความผิดปกติของภาพ/เสียง (Deepfake Check)**: ตรวจสอบการกะพริบตา แสงเงา ริมฝีปากที่ขยับไม่ตรงกับเสียง หรือความคมชัดบริเวณขอบใบหน้า
3. **ตรวจวันที่และบริบท**: ข่าวเก่าถูกนำมาแชร์ซ้ำเพื่อสร้างกระแสความกลัวหรือไม่
4. **เปรียบเทียบข้อมูลหลายสำนัก**: มีหน่วยงานทางการหรือสำนักข่าวหลักรายงานตรงกันหรือไม่
5. **ระวังพาดหัวแบบ Clickbait**: ข่าวที่ใช้คำกระตุ้นอารมณ์โกรธ ตกใจ หรือเร่งเร้าให้รีบส่งต่อ มักแฝงข้อมูลเท็จ`;
  }

  if (p.includes('cyberbullying') || p.includes('กลั่นแกล้ง') || p.includes('บูลลี่') || p.includes('คุกคาม') || p.includes('นินทา')) {
    return `🛡️ **วิธีรับมือเมื่อพบการกลั่นแกล้งบนโลกไซเบอร์ (Cyberbullying Management)**:

1. **Stop (หยุด)**: ไม่ตอบโต้ด้วยอารมณ์หรือคำด่าทอกลับคืน เพราะจะกระตุ้นให้อีกฝ่ายระรานมากขึ้น
2. **Save (บันทึกหลักฐาน)**: แคปภาพหน้าจอ ข้อความ บัญชีผู้กระทำ ลิงก์ และเวลาที่เกิดเหตุไว้ให้ชัดเจน
3. **Block (บล็อก)**: ปิดกั้นช่องทางการติดต่อจากบัญชีที่มาคุกคามทันที
4. **Report (รายงาน)**: กด Report ต่อระบบโซเชียลมีเดีย และหากรุนแรงให้แจ้งคุณครู ผู้ปกครอง หรือศูนย์รับเรื่องร้องเรียนภัยออนไลน์ (1212)
5. **Support (เคียงข้างเพื่อน)**: หากเห็นเพื่อนถูกบูลลี่ อย่าส่งต่อข้อความซ้ำเติม และทักแชตไปให้กำลังใจเพื่อนเสมอ`;
  }

  if (p.includes('รหัสผ่าน') || p.includes('password') || p.includes('phishing') || p.includes('ลิงก์') || p.includes('แฮก') || p.includes('ยืมเงิน')) {
    return `🔐 **แนวทาง Cybersecurity Management รับมือลิงก์หลอกและบัญชีถูกสวมรอย**:

- **กรณีเจอลิงก์แปลกใน SMS/แชต**: ห้ามกดลิงก์เด็ดขาด สังเกตชื่อโดเมน หากลงท้ายด้วย .xyz, .top หรือสะกดเพี้ยน (เช่น www.scb-verify.xyz) เป็นของปลอม 100%
- **กรณีเพื่อนทักมาขอยืมเงินด่วน**: สันนิษฐานไว้ก่อนว่า "บัญชีเพื่อนอาจโดนแฮก" ให้โทรศัพท์คุยหรือวิดีโอคอลเพื่อยืนยันตัวตนจริงก่อนเสมอ
- **การตั้งรหัสผ่าน**: ยาวอย่างน้อย 12 ตัวอักษร ผสมตัวพิมพ์ใหญ่-เล็ก ตัวเลข และสัญลักษณ์พิเศษ
- **เปิดใช้งาน 2FA (Two-Factor Authentication)**: ในทุกบัญชีสำคัญ เช่น Google, LINE, Facebook, และแอปธนาคาร`;
  }

  if (p.includes('footprint') || p.includes('ร่องรอย') || p.includes('ประวัติ') || p.includes('ลบได้')) {
    return `👣 **Digital Footprints (ร่องรอยดิจิทัล) ลบได้จริงไหม?**:

คำตอบคือ **"ลบได้ยากมากและแทบไม่มีทางหายไป 100%"** ครับ:
- แม้คุณจะกดลบโพสต์ไปแล้ว แต่เซิร์ฟเวอร์อาจยังสำรองข้อมูลไว้ และผู้ใช้งานคนอื่นอาจแคปหน้าจอไว้เรียบร้อยแล้ว
- ปัจจุบันฝ่ายบุคคล (HR) และคณะกรรมการคัดเลือกทุนการศึกษา มีการตรวจสอบประวัติโซเชียลย้อนหลังของผู้สมัคร
- **กฎทองของพลเมืองดิจิทัล**: "ถ้าไม่กล้าพูดประโยคนี้ต่อหน้าทุกคนในชีวิตจริง ก็ไม่ควรพิมพ์ลงบนโลกออนไลน์"
- พยายามสร้าง **Positive Digital Footprints** เช่น การแชร์ผลงานวิชาการ จิตอาสา และทักษะความรู้ที่เป็นประโยชน์`;
  }

  if (p.includes('เวลา') || p.includes('screen time') || p.includes('ติดจอ') || p.includes('มือถือ') || p.includes('นอนไม่หลับ')) {
    return `⏱️ **เทคนิค Screen Time Management เพื่อความสมดุล Online/Offline**:

1. **กฎ 20-20-20**: ทุก 20 นาทีที่มองจอ ให้พักสายตามองไปที่วัตถุไกล 20 ฟุต นาน 20 วินาที เพื่อคลายกล้ามเนื้อตา
2. **กฎงดจอก่อนนอน**: วางโทรศัพท์ไว้นอกเตียงก่อนเวลานอนอย่างน้อย 30-60 นาที เพื่อให้สมองหลั่งฮอร์โมนเมลาโทนินตามธรรมชาติ
3. **ปิดการแจ้งเตือน (Notifications)**: ปิดแจ้งเตือนแอปที่ไม่จำเป็นระหว่างอ่านหนังสือหรือทำการบ้าน
4. **กำหนดเวลาด้วย Digital Wellbeing / Screen Time**: ตั้งค่าจำกัดเวลาการเล่นแอปโซเชียลไม่ให้เกินวันละ 1-2 ชั่วโมง`;
  }

  if (p.includes('privacy') || p.includes('ส่วนตัว') || p.includes('pdpa') || p.includes('รูป')) {
    return `🔒 **Privacy Management (การจัดการความเป็นส่วนตัว)**:

1. **ขอความยินยอม (Consent) เสมอ**: ก่อนจะถ่ายรูปและโพสต์ภาพเพื่อนลงโซเชียล ควรถามความสะดวกใจของเพื่อนก่อน
2. **ระวังสิ่งของที่มีข้อมูลอ่อนไหว**: ห้ามโพสต์ภาพตั๋วเครื่องบิน (มีบาร์โค้ด PNR), บัตรประชาชน, บัตรคอนเสิร์ต, หรือหน้าสมุดบัญชี
3. **ตั้งค่าความเป็นส่วนตัว**: ตรวจสอบว่าแอปในมือถือขอสิทธิ์เข้าถึงอะไรบ้าง หากเป็นแอปแต่งรูปธรรมดาแต่ขอสิทธิ์ดูรายชื่อโทรศัพท์หรือ GPS ตลอดเวลา ให้กดปฏิเสธทันที`;
  }

  if (p.includes('empathy') || p.includes('ใจ') || p.includes('คอมเมนต์') || p.includes('ทัวร์ลง')) {
    return `❤️ **Digital Empathy (ความเห็นอกเห็นใจบนโลกดิจิทัล)**:

- ตระหนักเสมอว่า **"เบื้องหลังทุกโปรไฟล์คือมนุษย์ที่มีหัวใจ มีความรู้สึก และเจ็บปวดได้เช่นเดียวกับเรา"**
- คิดแทนคนอ่านก่อนกดส่ง: ถ้อยคำสั้นๆ ที่เราพิมพ์ด้วยความคึกคะนอง อาจกลายเป็นตราบาปติดตัวผู้รับไปตลอดชีวิต
- หลีกเลี่ยงกระแสทัวร์ลง (Cancel Culture) ที่ตั้งอยู่บนคลิปสั้นเพียงไม่กี่วินาทีโดยไม่ทราบข้อเท็จจริงรอบด้าน`;
  }

  return `สวัสดีครับ! ผมคือ **DQ Buddy** เพื่อนคู่คิดด้านความฉลาดทางดิจิทัล 🤖✨

ผมพร้อมให้คำปรึกษาและตอบคำถามเกี่ยวกับ **8 ทักษะความฉลาดทางดิจิทัล (DQ)** ตามกรอบ สสวท.:
1. เอกลักษณ์พลเมืองดิจิทัล (Digital Citizen Identity)
2. การบริหารเวลาหน้าจอ (Screen Time Management)
3. การจัดการการกลั่นแกล้งบนไซเบอร์ (Cyberbullying Management)
4. การจัดการความปลอดภัยไซเบอร์ (Cybersecurity Management)
5. การจัดการความเป็นส่วนตัว (Privacy Management)
6. การคิดอย่างมีวิจารณญาณ (Critical Thinking)
7. ร่องรอยดิจิทัล (Digital Footprints)
8. ความเห็นอกเห็นใจบนโลกดิจิทัล (Digital Empathy)

ลองพิมพ์ถามคำศัพท์ สถานการณ์จริงที่กำลังพบเจอ หรือขอแนวทางการใช้อินเทอร์เน็ตอย่างปลอดภัยได้เลยครับ!`;
}
